/**
 * Generates lib/demo/apiRegistry.ts: every route handler under app/api/v1, as static imports, so
 * the demo bridge can run a handler inside the page function (see lib/demo/bridge.ts).
 *   node scripts/gen-api-registry.mjs          write the file
 *   node scripts/gen-api-registry.mjs --check  exit 1 if the file is out of date
 */
import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import path from "node:path";

const root = "app/api/v1";
const files = [];
const walk = (d) => {
  for (const f of readdirSync(d).sort()) {
    const p = path.join(d, f);
    if (statSync(p).isDirectory()) walk(p);
    else if (f === "route.ts") files.push(p);
  }
};
walk(root);

const lines = files.map((f, i) => {
  const route = "/" + path.dirname(path.relative(root, f)).split(path.sep).join("/");
  const pattern = route === "/." ? "/" : route;
  const methods = [...readFileSync(f, "utf8").matchAll(/export const (GET|POST|PATCH|PUT|DELETE)\b/g)].map((m) => m[1]);
  return { i, f, pattern, methods };
});

const out = `// Generated by scripts/gen-api-registry.mjs; do not edit.
/* eslint-disable */
${lines.map((l) => `import * as r${l.i} from "@/${l.f.replace(/\.ts$/, "")}";`).join("\n")}

export type Handler = (req: Request, ctx: { params: Promise<Record<string, string>> }) => Promise<Response>;
export type Entry = { pattern: string; methods: Partial<Record<string, Handler>> };

export const API_ROUTES: Entry[] = [
${lines.map((l) => `  { pattern: ${JSON.stringify(l.pattern)}, methods: { ${l.methods.map((m) => `${m}: r${l.i}.${m} as unknown as Handler`).join(", ")} } },`).join("\n")}
];
`;

const target = "lib/demo/apiRegistry.ts";
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {}
  if (current !== out) {
    console.error(`${target} is out of date: run node scripts/gen-api-registry.mjs`);
    process.exit(1);
  }
  console.log(`${target} is up to date (${lines.length} routes)`);
} else {
  writeFileSync(target, out);
  console.log(`wrote ${target} (${lines.length} routes)`);
}
